#!/bin/bash
# SessionStart hook: give Claude a map of the Obsidian vault (this repository), its
# visibility, and memory that other sessions committed to branches this checkout lacks.
# Read-only. Always exits 0 so a network failure never blocks the session.
set -uo pipefail
cd "${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}" 2>/dev/null || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

max_notes="${VAULT_MANIFEST_MAX:-400}"
max_inline="${VAULT_INLINE_MAX:-6000}"
# Unquoted paths: notes named in non-ASCII scripts must print as written.
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=core.quotepath GIT_CONFIG_VALUE_0=off
run() { if command -v timeout >/dev/null 2>&1; then timeout "$@"; else shift; "$@"; fi; }

echo "# Vault context (generated by .claude/hooks/vault-context.sh)"
echo

# 1. Visibility: an unauthenticated API call sees public repos only.
slug=$(git remote get-url origin 2>/dev/null | sed -E 's#\.git$##' | awk -F'[/:]' '{print $(NF-1)"/"$NF}')
code=$(curl -s -o /dev/null -m 8 -w '%{http_code}' "https://api.github.com/repos/$slug" 2>/dev/null)
echo "## Visibility"
case "$code" in
  200) echo "github.com/$slug is PUBLIC. Commit no vault notes, matter files, or personal facts; tell the user." ;;
  404) echo "github.com/$slug is private (unauthenticated GitHub API: 404). Vault notes may be committed." ;;
  *)   echo "Unverified (GitHub API HTTP ${code:-none}). Treat the repository as public." ;;
esac
echo

# 2. Memory on other branches: each session pushes to its own branch, so its notes and
#    lessons are absent from the next session's checkout until merged.
echo "## Commits on other branches not in this checkout"
run 25 git fetch -q --prune origin '+refs/heads/*:refs/remotes/origin/*' 2>/dev/null
found=0
while IFS= read -r ref; do
  [ "$ref" = "origin/HEAD" ] && continue
  git merge-base --is-ancestor "$ref" HEAD 2>/dev/null && continue
  found=1
  n=$(git rev-list --count "HEAD..$ref" 2>/dev/null || echo "?")
  when=$(git log -1 --format=%cs "$ref" 2>/dev/null)
  echo "### $ref ($n commit(s), last $when)"
  changed=$(git diff --name-status "HEAD...$ref" 2>/dev/null)
  if [ -z "$changed" ]; then
    echo "(history too shallow to diff; inspect with: git log HEAD..$ref --stat)"
    continue
  fi
  echo "$changed" | sed 's/^/    /'
  # Inline lessons and notes this branch added or changed, so their content is known now.
  budget=$max_inline
  echo "$changed" | awk -F'\t' '$1 ~ /^[AM]/ && $NF ~ /\.md$/ && $NF !~ /^matters\// {print $NF}' |
  while IFS= read -r f; do
    body=$(git show "$ref:$f" 2>/dev/null) || continue
    if [ "${#body}" -gt "$budget" ]; then
      echo "#### $f: ${#body} chars, not inlined; read with: git show $ref:$f"
      continue
    fi
    budget=$((budget - ${#body}))
    printf '#### %s\n%s\n' "$f" "$body"
  done
done < <(git for-each-ref --format='%(refname:short)' refs/remotes/origin)
[ "$found" = 0 ] && echo "None: this checkout contains every remote branch."
echo

# 3. Note manifest: path and title (frontmatter title, else first heading, else filename).
echo "## Notes"
notes=$(git ls-files --cached --others --exclude-standard -- '*.md' '*.canvas' | grep -v '^\.claude/')
total=$(printf '%s' "$notes" | grep -c . || true)
echo "$total note(s). One line each: path | title. Search content before answering; this is a map, not the text."
if [ "$total" -gt 0 ]; then
  shown=$(printf '%s\n' "$notes" | head -n "$max_notes")
  # Titles keyed by path; empty files yield no awk record, so the join below falls back to the filename.
  titles=$(printf '%s\n' "$shown" | tr '\n' '\0' | xargs -0 awk '
    FNR == 1 { if (prev != "" && t != "") print prev "\t" t; prev = FILENAME; t = ""; fm = 0 }
    FNR == 1 && /^---[ \t]*$/ { fm = 1; next }
    fm && /^---[ \t]*$/ { fm = 0; next }
    fm && t == "" && /^title:/ { t = $0; sub(/^title:[ \t]*/, "", t); gsub(/^["\047]|["\047]$/, "", t); next }
    !fm && t == "" && /^#[ \t]/ { t = $0; sub(/^#[ \t]+/, "", t) }
    END { if (prev != "" && t != "") print prev "\t" t }' 2>/dev/null)
  printf '%s\n' "$shown" | awk -F'\t' 'NR == FNR { t[$1] = $2; next }
    { b = $0; sub(/.*\//, "", b); sub(/\.(md|canvas)$/, "", b); print $0 " | " (($0 in t) ? t[$0] : b) }' \
    <(printf '%s\n' "$titles") -
  [ "$total" -gt "$max_notes" ] && echo "... $((total - max_notes)) more; list with: git ls-files '*.md'"
fi
other=$(git ls-files | grep -vE '\.(md|canvas)$' | grep -vE '^(\.claude/|\.obsidian/|scripts/|\.git)' | grep -vE '^\.vault-manifest\.tsv$|(^|/)\.gitkeep$')
if [ -n "$other" ]; then
  echo
  echo "Attachments by type:"
  printf '%s\n' "$other" | awk -F. 'NF > 1 {print tolower($NF)} NF == 1 {print "(none)"}' | sort | uniq -c | sort -rn | awk '{printf "    %s %s\n", $1, $2}'
fi
[ -f .vault-manifest.tsv ] && echo && echo "Original file timestamps and sha256 hashes from the import: .vault-manifest.tsv (git does not keep mtimes)."
exit 0
